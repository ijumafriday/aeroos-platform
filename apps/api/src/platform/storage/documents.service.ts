import { Inject, Injectable } from '@nestjs/common';
import { and, asc, desc, eq, inArray, lt, or } from 'drizzle-orm';
import type { DocumentDto, UploadTicketDto } from '@aeroos/contracts';
import { DomainError, newId, sha256Hex } from '@aeroos/kernel';
import { CONFIG, type Config } from '../../config';
import { actorOf, type Principal } from '../auth/principal';
import { AuditService } from '../audit/audit.service';
import { AuthzService } from '../authz/authz.service';
import { DB_TOKEN, type ModuleDb } from '../database/module-db';
import { documents } from '../database/platform.tables';
import { Metrics } from '../observability/metrics';
import { ObjectStore } from './object-store';

/** What can own a document. Each owner type has its own rules in infra/cerbos/policies/document.yaml. */
export const OWNER_TYPES = ['task_card', 'crs', 'training_record', 'licence', 'personnel', 'directive', 'manual_revision', 'ncr', 'technical_record'] as const;
export type OwnerType = (typeof OWNER_TYPES)[number];

export const ALLOWED_CONTENT_TYPES = ['application/pdf', 'image/png', 'image/jpeg'] as const;

const CHAIN = 'documents';
type Row = typeof documents.$inferSelect;

export const documentDto = (r: Row): DocumentDto => ({
  id: r.id, ownerType: r.ownerType, ownerId: r.ownerId, fileName: r.fileName, contentType: r.contentType, sizeBytes: r.sizeBytes,
  sha256: r.sha256, status: r.status as DocumentDto['status'], uploadedBy: r.uploadedBy, createdAt: r.createdAt.toISOString()
});

const safeName = (n: string) => n.replace(/[^\w.-]+/g, '_').slice(0, 120) || 'file';

/**
 * The document register. Bytes go browser → object storage directly (presigned PUT), never through
 * the API; the API registers the document, then on confirmation hashes the stored object and writes
 * the hash to the "documents" audit chain. A document is evidence only once it is STORED with a hash.
 */
@Injectable()
export class DocumentsService {
  constructor(
    @Inject(DB_TOKEN.platform) private readonly db: ModuleDb,
    @Inject(CONFIG) private readonly config: Config,
    private readonly store: ObjectStore,
    private readonly authz: AuthzService,
    private readonly audit: AuditService
  ) {}

  private resource(operatorId: string, ownerType: string, id = '*') {
    return { kind: 'document' as const, id, attr: { operatorId, ownerType } };
  }

  async createUpload(p: Principal, i: { ownerType: OwnerType; ownerId: string; fileName: string; contentType: string; sizeBytes: number }): Promise<UploadTicketDto> {
    if (i.ownerType === 'crs') throw new DomainError('GENERATED_ONLY', 'CRS documents are generated by the system, not uploaded', 422);
    if (!(ALLOWED_CONTENT_TYPES as readonly string[]).includes(i.contentType)) {
      throw new DomainError('CONTENT_TYPE', `Only ${ALLOWED_CONTENT_TYPES.join(', ')} can be stored`, 422);
    }
    if (i.sizeBytes <= 0 || i.sizeBytes > this.config.DOCUMENT_MAX_BYTES) {
      throw new DomainError('TOO_LARGE', `Files must be between 1 byte and ${Math.round(this.config.DOCUMENT_MAX_BYTES / 1048576)} MB`, 422);
    }
    await this.authz.check(p, this.resource(p.operatorId, i.ownerType), 'attach');
    const id = `DOC-${newId()}`;
    const objectKey = `${p.operatorId}/${i.ownerType}/${safeName(i.ownerId)}/${id}/${safeName(i.fileName)}`;
    const [row] = await this.db.db.insert(documents).values({
      id, operatorId: p.operatorId, ownerType: i.ownerType, ownerId: i.ownerId, kind: 'attachment', fileName: i.fileName.slice(0, 200),
      contentType: i.contentType, objectKey, sizeBytes: i.sizeBytes, sha256: null, status: 'PENDING', uploadedBy: actorOf(p)
    }).returning();
    const expiresIn = 900;
    const put = await this.store.presignPut(objectKey, i.contentType, expiresIn);
    return { document: documentDto(row), uploadUrl: put.url, headers: put.headers, expiresAt: new Date(Date.now() + expiresIn * 1000).toISOString() };
  }

  /** Called by the browser after its PUT succeeded. Hashes what was actually stored. */
  async confirm(p: Principal, id: string): Promise<DocumentDto> {
    const doc = await this.require(id, p.operatorId);
    await this.authz.check(p, this.resource(doc.operatorId, doc.ownerType, id), 'attach');
    if (doc.status === 'STORED') return documentDto(doc);
    if (doc.status === 'EXPIRED') throw new DomainError('UPLOAD_EXPIRED', 'This upload expired; upload the file again', 409);
    const head = await this.store.head(doc.objectKey);
    if (!head) throw new DomainError('NOT_UPLOADED', 'The file has not arrived in storage yet; retry the upload', 409);
    const { sha256, size } = await this.store.sha256(doc.objectKey, this.config.DOCUMENT_MAX_BYTES);
    return this.db.transaction(async () => {
      const [row] = await this.db.db.update(documents).set({ status: 'STORED', sha256, sizeBytes: size, storedAt: new Date() })
        .where(and(eq(documents.id, id), eq(documents.status, 'PENDING'))).returning();
      if (!row) return documentDto(await this.require(id, p.operatorId));
      await this.audit.record(this.db, CHAIN, { operatorId: doc.operatorId,
        actor: actorOf(p), action: 'document.stored', entityType: doc.ownerType, entityId: doc.ownerId,
        data: { documentId: id, fileName: doc.fileName, contentType: doc.contentType, sizeBytes: size, sha256 }
      });
      return documentDto(row);
    });
  }

  /**
   * System-generated documents (the CRS PDF). Idempotent per owner: a redelivered event returns the
   * document that already exists instead of writing a second one.
   */
  async storeGenerated(i: { operatorId: string; ownerType: OwnerType; ownerId: string; fileName: string; contentType: string; bytes: Uint8Array; actor: string }): Promise<DocumentDto> {
    const [existing] = await this.db.db.select().from(documents)
      .where(and(eq(documents.ownerType, i.ownerType), eq(documents.ownerId, i.ownerId), eq(documents.kind, 'generated'))).limit(1);
    if (existing?.status === 'STORED') return documentDto(existing);
    const id = existing?.id ?? `DOC-${newId()}`;
    const objectKey = existing?.objectKey ?? `${i.operatorId}/${i.ownerType}/${safeName(i.ownerId)}/${id}/${safeName(i.fileName)}`;
    await this.store.putDocument(objectKey, i.bytes, i.contentType);
    const sha256 = sha256Hex(i.bytes);
    return this.db.transaction(async () => {
      const values = {
        id, operatorId: i.operatorId, ownerType: i.ownerType, ownerId: i.ownerId, kind: 'generated', fileName: i.fileName, contentType: i.contentType,
        objectKey, sizeBytes: i.bytes.length, sha256, status: 'STORED', uploadedBy: i.actor, storedAt: new Date()
      };
      const [row] = await this.db.db.insert(documents).values(values)
        .onConflictDoUpdate({ target: documents.id, set: { sha256, sizeBytes: i.bytes.length, status: 'STORED', storedAt: new Date() } })
        .returning();
      await this.audit.record(this.db, CHAIN, { operatorId: i.operatorId,
        actor: i.actor, action: 'document.generated', entityType: i.ownerType, entityId: i.ownerId,
        data: { documentId: id, fileName: i.fileName, contentType: i.contentType, sizeBytes: i.bytes.length, sha256 }
      });
      return documentDto(row);
    });
  }

  /**
   * Hourly sweep of uploads still PENDING well after their ticket expired (15 min). If the file did
   * arrive (the browser's confirm call was lost), it is hashed and stored as the user meant; otherwise
   * the register entry is marked EXPIRED. Both outcomes are on the documents audit chain.
   */
  async sweepPending(olderThanMinutes = 60): Promise<{ stored: number; expired: number }> {
    const rows = await this.db.db.select().from(documents)
      .where(and(eq(documents.status, 'PENDING'), lt(documents.createdAt, new Date(Date.now() - olderThanMinutes * 60_000))))
      .orderBy(asc(documents.createdAt)).limit(500);
    const out = { stored: 0, expired: 0 };
    for (const doc of rows) {
      const head = await this.store.head(doc.objectKey).catch(() => undefined);
      if (head === undefined) continue; // storage unreachable: decide next hour, never expire on an error
      let hashed: { sha256: string; size: number } | null = null;
      if (head) {
        try {
          hashed = await this.store.sha256(doc.objectKey, this.config.DOCUMENT_MAX_BYTES);
        } catch {
          continue; // the file is there but could not be read now (or is over the size limit): leave it PENDING
        }
      }
      await this.db.transaction(async () => {
        const [row] = await this.db.db.update(documents)
          .set(hashed ? { status: 'STORED', sha256: hashed.sha256, sizeBytes: hashed.size, storedAt: new Date() } : { status: 'EXPIRED' })
          .where(and(eq(documents.id, doc.id), eq(documents.status, 'PENDING'))).returning({ id: documents.id });
        if (!row) return;
        await this.audit.record(this.db, CHAIN, { operatorId: doc.operatorId,
          actor: 'system:upload-sweep', action: hashed ? 'document.stored' : 'document.upload_expired', entityType: doc.ownerType, entityId: doc.ownerId,
          data: hashed
            ? { documentId: doc.id, fileName: doc.fileName, contentType: doc.contentType, sizeBytes: hashed.size, sha256: hashed.sha256, uploadedBy: doc.uploadedBy, note: 'Upload arrived but was never confirmed; stored by the sweep' }
            : { documentId: doc.id, fileName: doc.fileName, uploadedBy: doc.uploadedBy, ticketIssuedAt: doc.createdAt.toISOString() }
        });
        if (hashed) out.stored++;
        else { out.expired++; Metrics.uploadsExpired.add(1); }
      });
    }
    return out;
  }

  async list(p: Principal, ownerType: string, ownerId: string): Promise<DocumentDto[]> {
    await this.authz.check(p, this.resource(p.operatorId, ownerType), 'read');
    const rows = await this.db.db.select().from(documents)
      .where(and(eq(documents.operatorId, p.operatorId), eq(documents.ownerType, ownerType), eq(documents.ownerId, ownerId), eq(documents.status, 'STORED')))
      .orderBy(desc(documents.createdAt));
    return rows.map(documentDto);
  }

  /** Latest stored document per owner — used by modules to show "has a scan" without N queries. */
  async latestFor(operatorId: string, owners: { type: string; id: string }[]): Promise<Map<string, DocumentDto>> {
    const out = new Map<string, DocumentDto>();
    if (!owners.length) return out;
    const rows = await this.db.db.select().from(documents).where(and(
      eq(documents.operatorId, operatorId),
      eq(documents.status, 'STORED'),
      or(...owners.map(o => and(eq(documents.ownerType, o.type), eq(documents.ownerId, o.id))))
    )).orderBy(desc(documents.createdAt));
    for (const r of rows) {
      const k = `${r.ownerType}:${r.ownerId}`;
      if (!out.has(k)) out.set(k, documentDto(r));
    }
    return out;
  }

  async allFor(operatorId: string, ownerType: string, ownerIds: string[]): Promise<DocumentDto[]> {
    if (!ownerIds.length) return [];
    const rows = await this.db.db.select().from(documents)
      .where(and(eq(documents.operatorId, operatorId), eq(documents.ownerType, ownerType), inArray(documents.ownerId, ownerIds), eq(documents.status, 'STORED')))
      .orderBy(desc(documents.createdAt));
    return rows.map(documentDto);
  }

  async downloadUrl(p: Principal, id: string): Promise<{ url: string; document: DocumentDto }> {
    const doc = await this.require(id, p.operatorId);
    await this.authz.check(p, this.resource(doc.operatorId, doc.ownerType, id), 'read');
    if (doc.status !== 'STORED') throw new DomainError('NOT_STORED', 'This document has not finished uploading', 409);
    return { url: await this.store.presignGet(doc.objectKey, doc.fileName), document: documentDto(doc) };
  }

  private async require(id: string, operatorId: string): Promise<Row> {
    const [r] = await this.db.db.select().from(documents).where(eq(documents.id, id)).limit(1);
    if (!r || r.operatorId !== operatorId) throw new DomainError('DOCUMENT_NOT_FOUND', `Document ${id} not found`, 404);
    return r;
  }
}
